#!/usr/bin/env python3
"""Statistics of the generation of the matrix A of ML-KEM, and constants of the selection rules.

The matrix A is made of k*k entries, each generated by SampleNTT (FIPS 203, Algorithm 7). An
iteration of its loop takes 3 bytes from SHAKE128 and yields 2 candidates, each accepted with
probability q/4096. A SHAKE128 block is 168 bytes, i.e. 56 iterations.

Modelling the XOF output as uniformly random, an entry needs more than n iterations exactly when
at most 255 of the first 2n candidates are accepted. Everything below derives from that exact
binomial tail. The per entry and the extra block distributions are exact fractions. The
distribution of the total number of iterations of a key is computed in double precision, which
is far more than enough for probabilities printed with 2 decimals of their base 2 logarithm.

See SPEC.md for the use of these numbers.
"""
import argparse
import functools
import math
from fractions import Fraction

Q = 3329
N_COEFFS = 256
ITER_PER_BLOCK = 56  # 168 bytes per SHAKE128 block, 3 bytes per iteration
MIN_BLOCKS = 3  # 128 iterations at least, 168 fit in 3 blocks
MAX_ITERATIONS = 280  # loop bound allowed by FIPS 203 Appendix B (5 blocks)
K = {512: 2, 768: 3, 1024: 4}
PSETS = tuple(K)

# Selection rules (SPEC.md): targets of the tiers of the worst case, and of the best case,
# as minus the base 2 logarithm of their probability.
PROFILES = {
    'v1': {'best': 28, 'tiers': (28, 35)},  # published test vectors
    'test': {'best': 10, 'tiers': (10, 16)},  # end to end tests only, never published
}


def blocks(iterations):
    """Number of SHAKE128 blocks consumed by an entry needing that many iterations."""
    return -(-iterations // ITER_PER_BLOCK)


@functools.lru_cache(maxsize=None)
def iterations_gt(n):
    """Exact probability that an entry needs more than n iterations."""
    if 2 * n < N_COEFFS:
        return Fraction(1)
    a, b = Q, 4096 - Q
    num = sum(math.comb(2 * n, i) * a**i * b ** (2 * n - i) for i in range(N_COEFFS))
    return Fraction(num, 4096 ** (2 * n))


# Every probability of an entry is an integer divided by 4096^(2 * MAX_ITERATIONS) = 2^SCALE_LOG2.
# Distributions are kept as such integers ("scaled"): exact, and much faster than fractions.
SCALE_LOG2 = 24 * MAX_ITERATIONS


def scaled_float(num, log2_den):
    """num / 2^log2_den as a float, for integers of any size."""
    shift = max(num.bit_length() - 64, 0)
    return math.ldexp(float(num >> shift), shift - log2_den)


def scaled_log2(num, log2_den):
    return math.log2(num) - log2_den


@functools.lru_cache(maxsize=None)
def entry_pmf_scaled():
    """Exact distribution of the number of iterations of one entry, {n: P(n) * 2^SCALE_LOG2}.

    Truncated at MAX_ITERATIONS: the missing mass is iterations_gt(MAX_ITERATIONS) = 2^-261.
    """
    out = {}
    for n in range(N_COEFFS // 2, MAX_ITERATIONS + 1):
        p = (iterations_gt(n - 1) - iterations_gt(n)) * (1 << SCALE_LOG2)
        assert p.denominator == 1
        out[n] = p.numerator
    return out


@functools.lru_cache(maxsize=None)
def entry_pmf():
    """Exact distribution of the number of iterations of one entry, {n: probability} (fractions)."""
    return {n: Fraction(v, 1 << SCALE_LOG2) for n, v in entry_pmf_scaled().items()}


@functools.lru_cache(maxsize=None)
def entry_moments():
    """Mean and variance of the number of iterations of one entry (exact fractions)."""
    pmf = entry_pmf()
    mean = sum(n * p for n, p in pmf.items())
    var = sum((n - mean) ** 2 * p for n, p in pmf.items())
    return mean, var


def p_extra_block():
    """Probability that an entry needs a 4th block."""
    return iterations_gt(MIN_BLOCKS * ITER_PER_BLOCK)


@functools.lru_cache(maxsize=None)
def entry_extra_scaled():
    """Exact distribution of the number of extra blocks of one entry, {x: P(x) * 2^SCALE_LOG2}."""
    out = {}
    for n, v in entry_pmf_scaled().items():
        x = blocks(n) - MIN_BLOCKS
        out[x] = out.get(x, 0) + v
    return out


@functools.lru_cache(maxsize=None)
def key_extra_scaled(k):
    """Exact distribution of e, the number of extra blocks of a key, {e: P(e) * 2^(k*k*SCALE_LOG2)}."""
    dist = {0: 1}
    for _ in range(k * k):
        nd = {}
        for e, p in dist.items():
            for x, q in entry_extra_scaled().items():
                nd[e + x] = nd.get(e + x, 0) + p * q
        dist = nd
    return dist


def key_extra_dist(k):
    """Distribution of e, {e: probability} as floats (exact values: key_extra_scaled)."""
    return {e: scaled_float(v, k * k * SCALE_LOG2) for e, v in key_extra_scaled(k).items()}


def p_extra_ge(k, x):
    """Exact probability that a key needs at least x extra blocks."""
    return Fraction(sum(v for e, v in key_extra_scaled(k).items() if e >= x), 1 << (k * k * SCALE_LOG2))


@functools.lru_cache(maxsize=None)
def key_fast_iterations(k):
    """Distribution of t, the total number of iterations of a key, restricted to keys without
    extra block: {t: P(e = 0 and t)}, in double precision."""
    fast = {n: float(p) for n, p in entry_pmf().items() if blocks(n) == MIN_BLOCKS}
    dist = {0: 1.0}
    for _ in range(k * k):
        nd = {}
        for t, p in dist.items():
            for n, q in fast.items():
                nd[t + n] = nd.get(t + n, 0.0) + p * q
        dist = nd
    return dist


def p_best(k, t_max):
    """Probability that a key has no extra block and at most t_max iterations."""
    return math.fsum(p for t, p in key_fast_iterations(k).items() if t <= t_max)


def log2(p):
    """Base 2 logarithm of a probability, exact fractions included (no underflow)."""
    if isinstance(p, Fraction):
        return math.log2(p.numerator) - math.log2(p.denominator)
    return math.log2(p)


def prob_str(p):
    """Probability as printed in the test vectors: 2^-28.18."""
    return f'2^{log2(p):.2f}'


@functools.lru_cache(maxsize=None)
def rules(pset, profile='v1'):
    """Constants of the selection rules of SPEC.md for a parameter set."""
    k = K[pset]
    prof = PROFILES[profile]
    # best case: largest T with P(e = 0 and t <= T) <= 2^-target
    target = 2.0 ** -prof['best']
    acc = 0.0
    t_best = None
    for t, p in sorted(key_fast_iterations(k).items()):
        acc += p
        if acc > target:
            break
        t_best = t
    # worst case: the number of extra blocks whose tail probability is the nearest to the target
    tiers = []
    for target_log2 in prof['tiers']:
        x = min(range(1, 2 * k * k + 1), key=lambda x: abs(log2(p_extra_ge(k, x)) + target_log2))
        if tiers and x == tiers[-1]['x']:
            continue  # nothing closer to this target than the previous tier
        tiers.append({'x': x, 'prob': prob_str(p_extra_ge(k, x))})
    # average set: N keys holding exactly X_avg extra blocks and S iterations
    period = round(1 / p_extra_block())  # 120 entries per extra block
    n_avg = next(n for n in range(1, period + 1) if n * k * k % period == 0)
    mean, _ = entry_moments()
    return {
        'profile': profile,
        'pset': pset,
        'k': k,
        'best': {'t': t_best, 'prob': prob_str(p_best(k, t_best))},
        'tiers': tuple(tiers),
        'average': {'n': n_avg, 'x': n_avg * k * k // period, 's': round(n_avg * k * k * mean)},
    }


def ncases(r):
    return 1 + len(r['tiers']) + r['average']['n']


def print_entry():
    mean, var = entry_moments()
    print('One entry of A:')
    print(f'  P(4th block)      = {float(p_extra_block()):.6%} = 1/{float(1 / p_extra_block()):.2f}')
    print(f'  P(5th block)      = {prob_str(iterations_gt(4 * ITER_PER_BLOCK))}')
    print(f'  P(more than {MAX_ITERATIONS} iterations) = {prob_str(iterations_gt(MAX_ITERATIONS))}')
    print(f'  iterations: mean {float(mean):.4f}, standard deviation {math.sqrt(var):.4f}')


def print_extra_blocks(xmax=8):
    print('\n| |' + '|'.join(f' ML-KEM-{p} ' for p in PSETS) + '|')
    print('|---|' + '---|' * len(PSETS))
    print('| P(no extra block) |' + '|'.join(f' {key_extra_dist(K[p])[0]:.1%} ' for p in PSETS) + '|')
    for x in range(1, xmax + 1):
        print(f'| P(at least {x}) |' + '|'.join(f' {prob_str(p_extra_ge(K[p], x))} ' for p in PSETS) + '|')


def print_rules(profile):
    rs = [rules(p, profile) for p in PSETS]
    print(f'\nRules, profile {profile}:')
    print('|  |' + '|'.join(f' ML-KEM-{p} ' for p in PSETS) + '|')
    print('|---|' + '---|' * len(PSETS))
    print('| Best: T, P(e = 0, t <= T) |' + '|'.join(f" {r['best']['t']}, {r['best']['prob']} " for r in rs) + '|')
    for i in range(max(len(r['tiers']) for r in rs)):
        cells = []
        for r in rs:
            cells.append(f" {r['tiers'][i]['x']}, {r['tiers'][i]['prob']} " if i < len(r['tiers']) else ' none ')
        print(f'| Worst tier {i + 1}: X, P(e >= X) |' + '|'.join(cells) + '|')
    print('| Average set: N, X_avg, S |' + '|'.join(f" {r['average']['n']}, {r['average']['x']}, {r['average']['s']} " for r in rs) + '|')
    print('| Test cases |' + '|'.join(f' {ncases(r)} ' for r in rs) + '|')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--profile', default='v1', choices=PROFILES)
    parser.add_argument('--thresholds', type=int, choices=PSETS, metavar='PSET',
                        help='print the thresholds of a search for the profile: --min-extra E --max-iters T')
    args = parser.parse_args()
    if args.thresholds:
        r = rules(args.thresholds, args.profile)
        print(f"--min-extra {r['tiers'][0]['x']} --max-iters {r['best']['t']}")
        raise SystemExit(0)
    print_entry()
    print_extra_blocks()
    print_rules(args.profile)
