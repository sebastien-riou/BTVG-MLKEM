"""Output formats of a set: C, JSON (ACVP layout) and SystemVerilog. The record is the Python format.

Every function returns the text of a file; the output only depends on the record (deterministic).
"""
import json

import mlkem_fips203
import mlkem_set

URL = 'https://github.com/sebastien-riou/BTVG-MLKEM'
C_HEADER = 'mlkem_test_vectors.h'
ROLE_NAMES = {'best': 'best case', 'worst': 'worst case', 'average': 'average set'}


def files(rec):
    """{file name: text} of every output of a set, the shared C header included."""
    full = [mlkem_set.full_values(rec['pset'], c) for c in rec['cases']]
    name = rec['name']
    return {
        f'{name}.py': mlkem_set.record_text(rec),
        f'{name}.c': c_data(rec),
        C_HEADER: c_header(),
        f'{name}-keyGen.json': json_keygen(rec, full),
        f'{name}-encapDecap.json': json_encapdecap(rec, full),
        f'{name}.sv': systemverilog(rec, full),
    }


def describe(rec, i):
    c = rec['cases'][i]
    what = ROLE_NAMES[c['role']] + (f" tier {c['tier']}" if c['role'] == 'worst' else '')
    prob = f", P = {c['probability']}" if c['probability'] else ''
    its = ' '.join(str(x) for x in c['iterations'])
    return f"case {i}: {what}, index {c['index']}{prob}, {c['e']} extra blocks, {c['t']} iterations ({its})"


def banner(rec, comment):
    lines = [
        f"BTVG-MLKEM test vectors {rec['name']}: ML-KEM-{rec['pset']}, {len(rec['cases'])} test cases.",
        f"Generated by BTVG-MLKEM {rec['version']} ({URL}) from {rec['name']}.py, do not edit.",
        f"Stream {rec['derivation']}, seed {rec['seed']}, selection rules {rec['rules']}: see SPEC.md.",
    ]
    return '\n'.join(f'{comment} {x}' for x in lines) + '\n'


# --- C ---------------------------------------------------------------------------------------------

def c_header():
    return f"""/* BTVG-MLKEM test vectors ({URL}): types of the C format, shared by every set.
 * Generated by BTVG-MLKEM, do not edit. See SPEC.md section 4. */
#ifndef MLKEM_TEST_VECTORS_H
#define MLKEM_TEST_VECTORS_H

#include <stdint.h>

#define MLKEM_TV_ROLE_BEST 0    /* the best case */
#define MLKEM_TV_ROLE_WORST 1   /* a worst case, of tier 1 or 2 */
#define MLKEM_TV_ROLE_AVERAGE 2 /* a key of the average set */

typedef struct {{
  uint8_t keygen_seed[64]; /* d || z, input of ML-KEM.KeyGen_internal */
  uint8_t encaps_seed[32]; /* m, input of ML-KEM.Encaps_internal */
  uint8_t pk_sha256[32];   /* SHA-256 of the encapsulation key ek */
  uint8_t sk_sha256[32];   /* SHA-256 of the decapsulation key dk */
  uint8_t ct_sha256[32];   /* SHA-256 of the ciphertext c */
  uint8_t ss[32];          /* shared secret K, output of encapsulation and of decapsulation of c */
  uint8_t ss_reject[32];   /* output of decapsulation of c', i.e. J(z || c') */
  uint16_t reject_bit;     /* c' is c with bit (reject_bit & 7) of byte (reject_bit >> 3) flipped */
  uint8_t role;            /* MLKEM_TV_ROLE_* */
  uint8_t tier;            /* 1 or 2 for a worst case, 0 otherwise */
}} mlkem_test_case_t;

typedef struct {{
  const char *name;
  unsigned int mlkem_pset;
  unsigned int ncases;
  const mlkem_test_case_t *cases;
}} mlkem_test_vectors_t;

#endif
"""


def c_bytes(hexstr):
    return '{' + ', '.join(f'0x{b:02X}' for b in bytes.fromhex(hexstr)) + '}'


def c_data(rec):
    pset = rec['pset']
    n = len(rec['cases'])
    roles = {'best': 'MLKEM_TV_ROLE_BEST', 'worst': 'MLKEM_TV_ROLE_WORST', 'average': 'MLKEM_TV_ROLE_AVERAGE'}
    out = ['/*\n' + banner(rec, ' *') + ' */', f'#include "{C_HEADER}"', '',
           f'static const mlkem_test_case_t mlkem{pset}_test_cases[{n}] = {{']
    for i, c in enumerate(rec['cases']):
        out += [
            f'{{ /* {describe(rec, i)} */',
            f".keygen_seed = {c_bytes(c['d'] + c['z'])},",
            f".encaps_seed = {c_bytes(c['m'])},",
            f".pk_sha256 = {c_bytes(c['pk_sha256'])},",
            f".sk_sha256 = {c_bytes(c['sk_sha256'])},",
            f".ct_sha256 = {c_bytes(c['ct_sha256'])},",
            f".ss = {c_bytes(c['ss'])},",
            f".ss_reject = {c_bytes(c['ss_reject'])},",
            f".reject_bit = {c['reject_bit']},",
            f".role = {roles[c['role']]},",
            f".tier = {c['tier']},",
            '},',
        ]
    out += ['};', '',
            f'const mlkem_test_vectors_t mlkem{pset}_test_vectors = {{',
            f'.name = "{rec["name"]}",',
            f'.mlkem_pset = {pset},',
            f'.ncases = {n},',
            f'.cases = mlkem{pset}_test_cases,',
            '};']
    return '\n'.join(out) + '\n'


# --- JSON, layout of ACVP (internalProjection) -----------------------------------------------------

def upper(b):
    return b.hex().upper() if isinstance(b, bytes) else b.upper()


def json_top(rec, mode, groups):
    top = {
        'vsId': 0,
        'algorithm': 'ML-KEM',
        'mode': mode,
        'revision': 'FIPS203',
        'isSample': True,
        'source': {
            'name': 'BTVG-MLKEM', 'url': URL, 'version': rec['version'], 'set': rec['name'],
            'digest': rec['digest'].upper(), 'derivation': rec['derivation'], 'seed': rec['seed'],
            'rules': rec['rules'],
        },
        'testGroups': groups,
    }
    return json.dumps(top, indent=2) + '\n'


def annotations(c, i):
    return {'case': i, 'role': c['role'], 'tier': c['tier']}


def json_keygen(rec, full):
    tests = []
    for i, (c, f) in enumerate(zip(rec['cases'], full)):
        t = {'tcId': i + 1, 'deferred': False, 'z': upper(c['z']), 'd': upper(c['d']), 'ek': upper(f['ek']),
             'dk': upper(f['dk'])}
        t.update(annotations(c, i))
        t.update({'index': c['index'], 'probability': c['probability'], 'extraBlocks': c['e'],
                  'iterations': c['t'], 'entryIterations': list(c['iterations'])})
        tests.append(t)
    group = {'tgId': 1, 'testType': 'AFT', 'parameterSet': f"ML-KEM-{rec['pset']}", 'tests': tests}
    return json_top(rec, 'keyGen', [group])


def json_encapdecap(rec, full):
    n = len(rec['cases'])
    encaps, decaps = [], []
    for i, (c, f) in enumerate(zip(rec['cases'], full)):
        t = {'tcId': i + 1, 'deferred': False, 'ek': upper(f['ek']), 'dk': upper(f['dk']), 'c': upper(f['c']),
             'k': upper(c['ss']), 'm': upper(c['m'])}
        t.update(annotations(c, i))
        encaps.append(t)
        for j, (ct, k, reason) in enumerate(((f['c'], c['ss'], 'valid decapsulation'),
                                             (f['c_reject'], c['ss_reject'], 'modified ciphertext'))):
            t = {'tcId': n + 2 * i + j + 1, 'deferred': False, 'ek': upper(f['ek']), 'dk': upper(f['dk']),
                 'c': upper(ct), 'k': upper(k), 'reason': reason}
            t.update(annotations(c, i))
            if j:
                t['rejectBit'] = c['reject_bit']
            decaps.append(t)
    pset = f"ML-KEM-{rec['pset']}"
    groups = [{'tgId': 1, 'testType': 'AFT', 'parameterSet': pset, 'function': 'encapsulation', 'tests': encaps},
              {'tgId': 2, 'testType': 'VAL', 'parameterSet': pset, 'function': 'decapsulation', 'tests': decaps}]
    return json_top(rec, 'encapDecap', groups)


# --- SystemVerilog ---------------------------------------------------------------------------------

SV_TYPES = {32: 'bytes32_t', 'EK_BYTES': 'ek_t', 'DK_BYTES': 'dk_t', 'CT_BYTES': 'ct_t'}


def sv_value(width, b):
    """A byte string as a packed array [LEN-1:0][7:0]: byte i is element [i]."""
    return f"{SV_TYPES[width]}'({8 * len(b)}'h{b[::-1].hex()})"


def systemverilog(rec, full):
    pset = rec['pset']
    k = mlkem_fips203.PARAMS[pset]['k']
    cases = rec['cases']
    n = len(cases)
    out = [banner(rec, '//').rstrip('\n'),
           '// Values are packed arrays of bytes: byte i of a value is its element [i].',
           '// Arrays indexed by test case: element [i] is test case i.',
           f"package {rec['name'].replace('-', '_')};",
           f'  localparam int MLKEM_PSET = {pset};',
           f'  localparam int K = {k};',
           f'  localparam int N_CASES = {n};',
           f'  localparam int EK_BYTES = {mlkem_fips203.ek_size(pset)};',
           f'  localparam int DK_BYTES = {mlkem_fips203.dk_size(pset)};',
           f'  localparam int CT_BYTES = {mlkem_fips203.ct_size(pset)};',
           '  localparam int ROLE_BEST = 0;',
           '  localparam int ROLE_WORST = 1;',
           '  localparam int ROLE_AVERAGE = 2;']
    for width, type_name in SV_TYPES.items():
        out.append(f'  typedef logic [{width}-1:0][7:0] {type_name};')

    def array(name, width, values, comment):
        out.append(f'  // {comment}')
        out.append(f'  localparam {SV_TYPES[width]} {name} [N_CASES] = \'{{')
        for i, v in enumerate(values):
            out.append(f"    {sv_value(width, v)}{',' if i < n - 1 else ''}")
        out.append('  };')

    def ints(name, values, comment):
        out.append(f'  // {comment}')
        out.append(f"  localparam int {name} [N_CASES] = '{{{', '.join(str(v) for v in values)}}};")

    def h(key):
        return [bytes.fromhex(c[key]) for c in cases]

    array('D', 32, h('d'), 'd, first input of ML-KEM.KeyGen_internal')
    array('Z', 32, h('z'), 'z, second input of ML-KEM.KeyGen_internal')
    array('M', 32, h('m'), 'm, input of ML-KEM.Encaps_internal')
    array('EK', 'EK_BYTES', [f['ek'] for f in full], 'encapsulation key ek')
    array('DK', 'DK_BYTES', [f['dk'] for f in full], 'decapsulation key dk')
    array('CT', 'CT_BYTES', [f['c'] for f in full], 'ciphertext c')
    array('SS', 32, h('ss'), 'shared secret K, output of encapsulation and of decapsulation of c')
    array('SS_REJECT', 32, h('ss_reject'), "output of decapsulation of c', i.e. J(z || c')")
    ints('REJECT_BIT', [c['reject_bit'] for c in cases],
         "c' is c with bit (REJECT_BIT % 8) of byte (REJECT_BIT / 8) flipped")
    array('PK_SHA256', 32, h('pk_sha256'), 'SHA-256 of ek')
    array('SK_SHA256', 32, h('sk_sha256'), 'SHA-256 of dk')
    array('CT_SHA256', 32, h('ct_sha256'), 'SHA-256 of c')
    roles = {'best': 'ROLE_BEST', 'worst': 'ROLE_WORST', 'average': 'ROLE_AVERAGE'}
    out.append('  // role of each test case')
    out.append(f"  localparam int ROLE [N_CASES] = '{{{', '.join(roles[c['role']] for c in cases)}}};")
    ints('TIER', [c['tier'] for c in cases], 'tier of a worst case (1 or 2), 0 otherwise')
    ints('EXTRA_BLOCKS', [c['e'] for c in cases], 'SHAKE128 blocks beyond 3 per entry, to generate A')
    ints('ITERATIONS', [c['t'] for c in cases], 'iterations of SampleNTT, to generate A')
    out.append('  // iterations of SampleNTT for each entry of A, row-major')
    out.append("  localparam int ENTRY_ITERATIONS [N_CASES][K*K] = '{")
    for i, c in enumerate(cases):
        out.append(f"    '{{{', '.join(str(x) for x in c['iterations'])}}}{',' if i < n - 1 else ''}  // {describe(rec, i)}")
    out.append('  };')
    out.append('endpackage')
    return '\n'.join(out) + '\n'
